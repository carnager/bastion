package io.github.carnager.bastion.data

/** A terminal color scheme: default foreground/background plus the 16 ANSI colors (RGB, no alpha). */
data class TermScheme(
    val id: String,
    val name: String,
    val background: Int,
    val foreground: Int,
    /** ANSI 0–7 then bright 8–15. */
    val ansi: List<Int>,
) {
    init {
        require(ansi.size == 16) { "$id needs 16 ANSI colors" }
    }

    val isLight: Boolean get() = luminance(background) > 0.5

    fun argb(rgb: Int): Int = rgb or (0xFF shl 24)
    val ansiArgb: IntArray get() = IntArray(16) { argb(ansi[it]) }

    companion object {
        fun luminance(rgb: Int): Double {
            val r = (rgb shr 16 and 0xFF) / 255.0
            val g = (rgb shr 8 and 0xFF) / 255.0
            val b = (rgb and 0xFF) / 255.0
            return 0.2126 * r + 0.7152 * g + 0.0722 * b
        }
    }
}

private fun scheme(id: String, name: String, bg: Int, fg: Int, vararg ansi: Int) = TermScheme(id, name, bg, fg, ansi.toList())

